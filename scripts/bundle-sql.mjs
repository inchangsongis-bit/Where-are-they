#!/usr/bin/env node
/**
 * Bundles every migration into one file you can paste into Supabase's SQL
 * editor, for when you would rather not clone the repo and install Node just
 * to create some tables.
 *
 * It records the same rows in schema_migrations that `pnpm migrate` would, so
 * a database set up this way and one set up with the runner are
 * indistinguishable — and `pnpm migrate` will correctly do nothing afterwards.
 *
 *   node scripts/bundle-sql.mjs > supabase/schema.sql
 */
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'supabase', 'migrations');
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();

const parts = [
  '-- Generated by scripts/bundle-sql.mjs — do not edit by hand.',
  '--',
  '-- Every migration, in order, plus the bookkeeping the migration runner',
  '-- keeps. Paste the whole thing into the Supabase SQL editor and run it once.',
  '--',
  '-- Re-running it will fail on the second statement, which is the point: the',
  '-- schema already exists and applying it twice would be wrong.',
  '',
  `create table if not exists schema_migrations (
  name        text primary key,
  checksum    text        not null,
  applied_at  timestamptz not null default now()
);`,
  '',
];

for (const file of files) {
  const sql = readFileSync(join(dir, file), 'utf8');
  const checksum = createHash('sha256').update(sql).digest('hex').slice(0, 16);

  parts.push(
    `-- ${'='.repeat(72)}`,
    `-- ${file}`,
    `-- ${'='.repeat(72)}`,
    '',
    sql.trimEnd(),
    '',
    `insert into schema_migrations (name, checksum) values ('${file}', '${checksum}')
  on conflict (name) do nothing;`,
    '',
  );
}

process.stdout.write(parts.join('\n'));
